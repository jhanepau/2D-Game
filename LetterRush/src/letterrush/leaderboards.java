    private void loadLeaderboard() {
    String url = "jdbc:derby://localhost:1527/user";
    String user = "root";
    String password = "root";

    try (Connection conn = DriverManager.getConnection(url, user, password);
         Statement stmt = conn.createStatement();
         ResultSet rs = stmt.executeQuery(
             "SELECT USERNAME, SUM(SCORE) AS TOTAL_SCORE " +
             "FROM USER_SCORES " +
             "WHERE CATEGORY = '" + currentCategory + "' " +
             "GROUP BY USERNAME " +
             "ORDER BY TOTAL_SCORE DESC, USERNAME ASC")) {

        StringBuilder leaderboardText = new StringBuilder();
        leaderboardText.append(String.format("%-21s %-30s %10s\n", "Rank", "Username", "Score"));
        leaderboardText.append("---------------------------------------------------------------------\n");

        int rank = 1;
        while (rs.next()) {
            String username = rs.getString("USERNAME");
            int score = rs.getInt("TOTAL_SCORE");

            String formattedLine = String.format("%-21d %-30s %10d\n", rank, username, score);
            leaderboardText.append(formattedLine);
            rank++;
        }

        leaderboardTextArea.setText(leaderboardText.toString());
        leaderboardTextArea.setEditable(false);
        leaderboardTextArea.setFont(new java.awt.Font("Monospaced", java.awt.Font.PLAIN, 12));
        leaderboardTextArea.setLineWrap(false);
        leaderboardTextArea.setWrapStyleWord(false);

        jScrollPane1.setViewportView(leaderboardTextArea);

    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(this, "Error loading leaderboard: " + ex.getMessage());
    }
}

    
    
