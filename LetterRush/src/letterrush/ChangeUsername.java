    private void changeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_changeActionPerformed
    String newUsername = newUsernamef.getText();  // Get the new username
    String currentUsername = currentUsernamef.getText();  // Get the current username from another field

    if (newUsername == null || newUsername.trim().isEmpty()) {
        showunEmptyScreen();
        return;
    }

    try {
        Class.forName("org.apache.derby.jdbc.ClientDriver");

        String url = "jdbc:derby://localhost:1527/user";
        String user = "root";
        String pass = "root";
        Connection conn = DriverManager.getConnection(url, user, pass);

        // Check if the new username already exists
        String checkSql = "SELECT * FROM USERS WHERE username=?";
        PreparedStatement checkPst = conn.prepareStatement(checkSql);
        checkPst.setString(1, newUsername);
        ResultSet rs = checkPst.executeQuery();

        if (rs.next()) {
            showDuplicateNameScreen();
            return;
        } else {
            // Ensure currentUsername is provided
            if (currentUsername == null || currentUsername.trim().isEmpty()) {
            showunReqScreen();
            return;
            }

            // Update username
            String updateSql = "UPDATE USERS SET username=? WHERE username=?";
            PreparedStatement updatePst = conn.prepareStatement(updateSql);
            updatePst.setString(1, newUsername);
            updatePst.setString(2, currentUsername);  // Set the current username

            int updatedRows = updatePst.executeUpdate();
            if (updatedRows > 0) {
                showunSuccesscreen();
                return;
            } else {
                showunFailedscreen();
            }
            updatePst.close();
        }

        rs.close();
        checkPst.close();
        conn.close();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
    }
    }//GEN-LAST:event_changeActionPerformed

