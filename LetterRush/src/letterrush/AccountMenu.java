    private void changeVolume(int volume) {
        if (volumeControl != null) {
        // Get the minimum and maximum values for the volume control
            float min = volumeControl.getMinimum();
            float max = volumeControl.getMaximum();
        
        // Calculate the new gain value based on the volume slider (0-100)
            float range = max - min;
            float gain = (range * volume / 100f) + min;

        // Set the new volume
            volumeControl.setValue(gain);
        }
    }
    private void musicslideStateChanged(javax.swing.event.ChangeEvent evt) {//GEN-FIRST:event_musicslideStateChanged
         volumeControl = AudioManager.getInstance().getVolumeControl();
        int sliderValue = musicslide.getValue();
        changeVolume(sliderValue);

    }//GEN-LAST:event_musicslideStateChanged

