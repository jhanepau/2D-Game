    private void okButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_okButtonActionPerformed
        String answer = answerField.getText().trim().toUpperCase();
        
        // Validate the answer
        if (answer.isEmpty()) {
            JOptionPane.showMessageDialog(this, "You must answer!");
        } else if (answer.equals("SPUTNIK 1")) {
            JOptionPane.showMessageDialog(this, "Correct! Sputnik 1 was the first artificial satellite.");
            this.dispose();  // Close the question form
            sm.resumeGame();  // Resume the game
        } else {
            JOptionPane.showMessageDialog(this, "Incorrect! The correct answer is Sputnik 1.");
            this.dispose();  // Close the question form
            sm.showGameOverScreen(username, currentLevel, this);

        }
    }//GEN-LAST:event_okButtonActionPerformed

