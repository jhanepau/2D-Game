    private void playActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_playActionPerformed
    String username = usernameField.getText();
    String password = new String(passwordField.getPassword());

    try {
        Class.forName("org.apache.derby.jdbc.ClientDriver");  

        String url = "jdbc:derby://localhost:1527/user";
        String user = "root";
        String pass = "root"; 
        Connection conn = DriverManager.getConnection(url, user, pass);

        String sql = "SELECT * FROM USERS WHERE username=? AND password=?";
        PreparedStatement pst = conn.prepareStatement(sql);
        pst.setString(1, username);
        pst.setString(2, password);
        ResultSet rs = pst.executeQuery();

        if (rs.next()) {
            boolean isFirstLogin = rs.getBoolean("FIRST_LOGIN");

            if (isFirstLogin) {
                // Give 30 coins and notify user
                showwelcomeCoins(username);

                // Add 30 coins
                int currentCoins = rs.getInt("COINS");
                int newCoinAmount = currentCoins + 30;

                // Update coins and mark as not first login
                String updateQuery = "UPDATE USERS SET COINS = ?, FIRST_LOGIN = FALSE WHERE USERNAME = ?";
                PreparedStatement updateStmt = conn.prepareStatement(updateQuery);
                updateStmt.setInt(1, newCoinAmount);
                updateStmt.setString(2, username);
                updateStmt.executeUpdate();
                updateStmt.close();
            }

            // Show login success screen
            showLoginScreen(username);
        } else {
            showloginfailedcreen();
        }

        rs.close();
        pst.close();
        conn.close();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Database Connection Error: " + e.getMessage());
        e.printStackTrace();
    }
    }//GEN-LAST:event_playActionPerformed

