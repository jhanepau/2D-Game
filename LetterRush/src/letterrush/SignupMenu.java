    private void nextActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_nextActionPerformed
    String emailInput = email.getText().trim();
    String username = usernameField.getText().trim();
    String password = new String(passwordField.getPassword()).trim();

    if (emailInput.isEmpty() || username.isEmpty() || password.isEmpty()) {
        showFieldsReqScreen();
        return;
    }

    if (password.length() < 8) {
        showEightPassScreen();
        return;
    }

    try {
        Class.forName("org.apache.derby.jdbc.ClientDriver");
        String url = "jdbc:derby://localhost:1527/user";
        String dbUser = "root";
        String dbPass = "root";

        Connection conn = DriverManager.getConnection(url, dbUser, dbPass);

        String checkQuery = "SELECT * FROM USERS WHERE LOWER(USERNAME) = LOWER(?)";
        PreparedStatement checkStmt = conn.prepareStatement(checkQuery);
        checkStmt.setString(1, username.trim()); // Trim again to be safe
        ResultSet result = checkStmt.executeQuery();

        if (result.next()) {
            showDuplicateNameScreen();
            result.close();
            checkStmt.close();
            conn.close();
            return;
        }

        result.close();
        checkStmt.close();

        // Insert new user
        String insertQuery = "INSERT INTO USERS (EMAIL, USERNAME, PASSWORD) VALUES (?, ?, ?)";
        PreparedStatement pst = conn.prepareStatement(insertQuery);
        pst.setString(1, emailInput);
        pst.setString(2, username);
        pst.setString(3, password);

        int rowsInserted = pst.executeUpdate();
        if (rowsInserted > 0) {
            showSignUpScreen();
        }

        pst.close();
        conn.close();
    } catch (Exception ex) {
        ex.printStackTrace();
        JOptionPane.showMessageDialog(this, "Something went wrong.\nDetails: " + ex.getMessage(),
                "Error", JOptionPane.ERROR_MESSAGE);
    }

    }//GEN-LAST:event_nextActionPerformed

