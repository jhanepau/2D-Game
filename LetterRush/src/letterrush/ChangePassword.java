    private void changeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_changeActionPerformed
         String currentUsername = usernamef.getText();  // Get the current username
    String newPassword = newPasswordf.getText();   // Get the new password

    // Validate input
    if (newPassword == null || newPassword.trim().isEmpty() || 
        currentUsername == null || currentUsername.trim().isEmpty()) {
        emptyUnPass tf = new emptyUnPass();
        tf.setVisible(true);
        tf.setLocationRelativeTo(null);
        return; // Exit method if fields are empty
    }

    try {
        // Load the JDBC driver
        Class.forName("org.apache.derby.jdbc.ClientDriver");

        // Connect to the database
        String url = "jdbc:derby://localhost:1527/user";
        String dbUser = "root";
        String dbPass = "root";
        Connection conn = DriverManager.getConnection(url, dbUser, dbPass);

        // Check if the user exists in the database
        String checkSql = "SELECT * FROM USERS WHERE username = ?";
        PreparedStatement checkPst = conn.prepareStatement(checkSql);
        checkPst.setString(1, currentUsername);
        ResultSet rs = checkPst.executeQuery();

        // If user doesn't exist, show 'not found' screen and return
        if (!rs.next()) {
            showNotFoundScreen(); // Show custom "username not found" screen
            rs.close();
            checkPst.close();
            conn.close();
            return; // Exit here to prevent further execution
        }

        // If user exists, proceed to update the password
        String updateSql = "UPDATE USERS SET password = ? WHERE username = ?";
        PreparedStatement updatePst = conn.prepareStatement(updateSql);
        updatePst.setString(1, newPassword);
        updatePst.setString(2, currentUsername);

        int updatedRows = updatePst.executeUpdate();

        if (updatedRows > 0) {
            // Success: password updated
            showSuccessScreen(); // Show custom "success" screen
        } else {
            // Failure: password update failed (could happen if no row was actually updated)
            showFailedScreen(); // Show custom "failed" screen
        }

        updatePst.close();
        rs.close();
        checkPst.close();
        conn.close();
    } catch (Exception e) {
        // If an error occurs, show a message
        JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
    }
    }//GEN-LAST:event_changeActionPerformed

