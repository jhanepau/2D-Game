    private void jComboBoxDifficultyActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jComboBoxDifficultyActionPerformed
        String selectedDifficulty = (String) jComboBoxDifficulty.getSelectedItem();
        DifficultyManager.setDifficulty(selectedDifficulty); // Store difficulty

        switch (selectedDifficulty) {
            case "Easy":
            letterFallSpeed = easySpeed;
            break;
            case "Medium":
            letterFallSpeed = mediumSpeed;
            break;
            case "Hard":
            letterFallSpeed = hardSpeed;
            break;
        }

        // Restart falling letters with the new speed
        if (letterFallTimer != null && letterFallTimer.isRunning()) {
            letterFallTimer.stop();
            startLetterFall();
        }
    }//GEN-LAST:event_jComboBoxDifficultyActionPerformed

