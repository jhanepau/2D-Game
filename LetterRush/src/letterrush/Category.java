    private int loadUserProgress(String username) {
    String filePath = "users.csv";

    try (BufferedReader br = new BufferedReader(new FileReader(filePath))) {
        String line;
        while ((line = br.readLine()) != null) {
            String[] data = line.split(",");
            if (data[0].equals(username)) {
                return Integer.parseInt(data[2]); // Return currentLevel
            }
        }
    } catch (IOException e) {
        e.printStackTrace();
    }

    return 1; // Default to Level 1 if no progress is found
}
    
    private void updateUserProgress(String username, int newLevel) {
    List<String[]> userData = new ArrayList<>();
    String filePath = "users.csv";

    try (BufferedReader br = new BufferedReader(new FileReader(filePath))) {
        String line;
        while ((line = br.readLine()) != null) {
            String[] data = line.split(","); // Corrected split format
            if (data[0].equals(username)) { 
                data[2] = String.valueOf(newLevel); // Update currentLevel
            }
            userData.add(data); // Store modified data
        }
    } catch (IOException e) {
        e.printStackTrace();
    }

    try (PrintWriter pw = new PrintWriter(new FileWriter(filePath))) {
        for (String[] row : userData) {
            pw.println(String.join(",", row));
        }
    } catch (IOException e) {
        e.printStackTrace();
    }      
    
}
    
    private boolean hasCompletedLevel(String username, int level) {
    String url = "jdbc:derby://localhost:1527/user";
    String user = "root";
    String password = "root";

    try (Connection conn = DriverManager.getConnection(url, user, password);
         PreparedStatement stmt = conn.prepareStatement(
            "SELECT SCORE FROM USER_SCORES WHERE USERNAME = ? AND LEVEL = ?")) {

        stmt.setString(1, username);
        stmt.setInt(2, level);

        ResultSet rs = stmt.executeQuery();
        return rs.next(); // If result exists, level is completed

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage());
        return false;
    }
}


    
